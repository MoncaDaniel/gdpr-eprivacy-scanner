"""Generate ``docs/legal/rule-catalog.md`` from the YAML catalog (ADR-0006).

    uv run python -m privacy_scanner.rules.catalog_docs > docs/legal/rule-catalog.md

A test asserts the committed file matches this output, so the document a
lawyer reviews can never drift from what the scanner applies.
"""

from __future__ import annotations

from privacy_scanner.domain.report import GuidanceReference, Regulation, RuleStatus
from privacy_scanner.rules.catalog_loader import RuleCatalog, default_catalog

_STATUS = {
    RuleStatus.AUTOMATED: "Automated",
    RuleStatus.MANUAL: "Manual review only",
    RuleStatus.PLANNED: "Planned",
}


def _guidance_line(g: GuidanceReference) -> str:
    title = f"[{g.authority}: {g.document}]({g.url})" if g.url else f"{g.authority}: {g.document}"
    pin = f", {g.pinpoint}" if g.pinpoint else ""
    binding = "binding" if g.binding else "non-binding"
    verified = f"verified {g.verified_on.isoformat()}" if g.verified_on else "**not yet verified**"
    return f"  - {title}{pin} — {g.jurisdiction}, {binding} {g.kind.replace('_', ' ')}; {verified}"


def render(catalog: RuleCatalog) -> str:
    info = catalog.info
    out = [
        "# Rule catalog",
        "",
        "<!-- Generated by `make docs` from src/privacy_scanner/rules/catalog/*.yaml. "
        "Do not edit by hand. -->",
        "",
        f"Catalog **v{info.version}**, law as of **{info.law_as_of.isoformat()}**, "
        f"SHA-256 `{info.sha256}`.",
        "",
        'Tiers: **A** deterministic; **B** heuristic (a low-confidence "Issue detected" '
        'becomes "Review suggested"); **M** not automatable (always "Review suggested"). '
        "Severity weights in the score: high 5, medium 3, low 1. See "
        "[methodology](methodology.md).",
        "",
    ]
    for regulation in Regulation:
        rules = catalog.for_regulation(regulation)
        out += [f"## {catalog.title_of(regulation)}", ""]
        out += ["| ID | Check | Tier | Severity | Status |", "|---|---|---|---|---|"]
        for r in rules:
            status = _STATUS[r.status]
            if r.status is RuleStatus.PLANNED:
                status += f" (phase {r.planned_phase})"
            out.append(
                f"| [{r.rule_id}](#{r.rule_id.lower()}) | {r.title} | {r.tier.value} | "
                f"{r.severity.value} | {status} |"
            )
        out.append("")
        for r in rules:
            out += [f"### {r.rule_id}", "", f"**{r.title}** · v{r.version}", ""]
            out.append(
                "- Legal basis: "
                + "; ".join(f"[{lb.instrument}, {lb.provision}]({lb.url})" for lb in r.legal_basis)
            )
            if r.guidance:
                out.append("- Interpretation:")
                out += [_guidance_line(g) for g in r.guidance]
            for key, text in r.explanations:
                out.append(f"- Wording when *{key.replace('_', ' ')}*: {text}")
            if r.review_prompt:
                out.append(f"- What to review: {r.review_prompt}")
            if r.remediation_hint:
                out.append(f"- Hint: {r.remediation_hint}")
            out.append("")
    out += ["## Always requires manual review (never scored)", ""]
    out += ["| ID | Topic | Provision | Reason |", "|---|---|---|---|"]
    out += [
        f"| {m.item_id} | {m.topic} | {m.provision} | {m.reason} |" for m in catalog.manual_items
    ]
    out += ["", "## Disclaimer printed on every report", "", catalog.disclaimer, ""]
    return "\n".join(out)


if __name__ == "__main__":  # pragma: no cover
    print(render(default_catalog()), end="")
